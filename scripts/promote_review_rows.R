#!/usr/bin/env Rscript
source('scripts/lib/common.R'); source('scripts/lib/validation.R')
source('scripts/lib/releases.R'); source('scripts/lib/promotion.R')
source('scripts/lib/runtime.R')
root <- pipeline_root(); check_runtime(root); args <- cli_args()
check_args(args,c('source','level','ids','country','reviewer','request-id','expected-release','apply'))
required <- c('source','ids','country','reviewer','request-id','expected-release')
if (any(!required %in% names(args))) stop('Required: --source, --ids, --country, --reviewer, --request-id, --expected-release')
if (any(vapply(args[required],is.logical,logical(1)))) stop('Required arguments need values')
result <- promote_rows(root,args$source,arg(args,'level',''),split_values(args$ids),args$country,args$reviewer,args[['request-id']],args[['expected-release']],isTRUE(arg(args,'apply',FALSE)))
cat(jsonlite::toJSON(result,auto_unbox=TRUE,pretty=TRUE,null='null'),'\n')
