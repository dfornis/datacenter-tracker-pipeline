#!/usr/bin/env Rscript
source('scripts/lib/common.R'); source('scripts/lib/validation.R'); source('scripts/lib/releases.R')
source('scripts/lib/accounting.R'); source('scripts/lib/geometry.R'); source('scripts/lib/export.R')
source('scripts/lib/runtime.R')
root <- pipeline_root(); check_runtime(root); args <- cli_args()
check_args(args,c('state','output-dir','apply','initialise-output'))
state <- arg(args,'state',if (is_symlink(file.path(root,'data/current'))) current_state(root) else NULL)
if (is.null(state)) stop('Initialise the validated data release before building, or pass --state for a staged validation')
output <- arg(args,'output-dir',file.path(root,'assets/data/datacenters'))
# A dedicated output lock serialises publishers; data itself is already immutable.
dir.create(file.path(root,'.locks'),showWarnings=FALSE)
lock <- file.path(root,'.locks','build')
if (!dir.create(lock,showWarnings=FALSE)) stop('Another build holds .locks/build; inspect before recovery')
result <- tryCatch(build_export(root,state,output,isTRUE(arg(args,'apply',FALSE)),isTRUE(arg(args,'initialise-output',FALSE))),finally=unlink(lock,recursive=TRUE))
cat(jsonlite::toJSON(result,auto_unbox=TRUE,pretty=TRUE),'\n')
