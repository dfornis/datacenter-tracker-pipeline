#!/usr/bin/env Rscript
source('scripts/lib/common.R')
source('scripts/lib/validation.R')
source('scripts/lib/releases.R')
source('scripts/lib/runtime.R')
root <- pipeline_root(); check_runtime(root)
args <- cli_args(); check_args(args, c('state'))
path <- arg(args, 'state', current_state(root))
if (file.exists(file.path(path, 'manifest.json'))) verify_release(path)
result <- validate_state(path, root)
cat(jsonlite::toJSON(result, auto_unbox = TRUE, pretty = TRUE), '\n')
